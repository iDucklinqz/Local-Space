export type Message = keyof typeof english;
let currentLocale: Locale = initialLocale();

function initialLocale(): Locale {
  const saved = localStorage.getItem('localspace-locale');
  if (saved === 'en' || saved === 'zh-CN') return saved;
  return navigator.language.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en';
}

export function getLocale(): Locale { return currentLocale; }
export function setLocale(locale: Locale): void {
  currentLocale = locale;
  localStorage.setItem('localspace-locale', locale);
  applyLocale();
}
export function applyLocale(): void {
  document.documentElement.lang = currentLocale;
  document.querySelector('meta[name="description"]')?.setAttribute('content', t('栖点 LocalSpace：把本地项目、分类与终端快捷入口放在一起的轻量工作台。'));
}
export function t(message: Message, values: Record<string, string | number> = {}): string {
  const translated: Translation = currentLocale === 'en' ? english[message] : message;
  const template = typeof translated === 'string' ? translated : translated[values.count === 1 ? 'one' : 'other'];
  return template.replace(/\{(\w+)\}/g, (match, key: string) => String(values[key] ?? match));
}
const defaults: Record<string, Message> = {
  frontend: '前端应用', backend: '后端服务', tools: '工具与脚本',
  game: '游戏开发', mobile: '移动应用', other: '其他项目',
};
export function categoryName(category?: Category): string {
  if (!category) return t('其他项目');
  return defaults[category.id] === category.name ? t(defaults[category.id]) : category.name;
}

