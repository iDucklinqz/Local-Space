const servicePatterns: [RegExp, (...values: string[]) => string][] = [
  [/^这个文件夹已添加为「(.*)」。$/s, name => `This folder is already registered as “${name}”.`],
  [/^无法访问目录：(.*)，请检查路径和权限。$/s, path => `Cannot access folder: ${path}. Check its path and permissions.`],
  [/^无法读取 (.*)$/s, path => `Cannot read ${path}`],
  [/^无法识别 (.*)$/s, path => `Cannot inspect ${path}`],
  [/^已达到本次扫描上限（(\d+) 个项目 \/ (\d+) 个目录），可缩小范围继续扫描。$/, (projects, directories) => `Scan limit reached (${projects} projects / ${directories} folders). Scan a smaller area to continue.`],
];
export function localizeMessage(message: string): string {
  if (currentLocale !== 'en') return message;
  if (Object.hasOwn(english, message)) return t(message as Message);
  if (Object.hasOwn(serviceMessages, message)) return serviceMessages[message];
  for (const [pattern, translate] of servicePatterns) {
    const match = message.match(pattern);
    if (match) return translate(...match.slice(1));
  }
  return message;
}
